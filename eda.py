import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Load Titanic dataset
df = pd.read_csv('/content/train.csv')

# Display first five rows
df.head()

# 1. Display dataset information
print("DATASET INFORMATION")
df.info()

# 2. Find the number of rows and columns
print("\nDATASET SHAPE:")
print(df.shape)

# 3. Generate statistical summary
print("\nSTATISTICAL SUMMARY:")
display(df.describe())

# 4. Check missing values
print("\nMISSING VALUES:")
print(df.isnull().sum())

# 5. Check duplicate records
print("\nDUPLICATE RECORDS:")
print(df.duplicated().sum())

# Survival Count

plt.figure(figsize=(7, 5))

sns.countplot(data=df, x='Survived', hue='Survived', palette='Set2', legend=False)

plt.title('Survival Count of Titanic Passengers')
plt.xlabel('Survival Status (0 = Not Survived, 1 = Survived)')
plt.ylabel('Number of Passengers')
plt.xticks([0, 1], ['Not Survived', 'Survived'])

plt.show()

plt.figure(figsize=(7, 5))

sns.countplot(data=df, x='Sex', hue='Survived', palette='Set2')

plt.title('Survival Count by Gender')
plt.xlabel('Gender')
plt.ylabel('Number of Passengers')
plt.legend(title='Survived', labels=['No', 'Yes'])

plt.show()

plt.figure(figsize=(7, 5))

sns.countplot(data=df, x='Pclass', hue='Survived', palette='Set2')

plt.title('Survival Count by Passenger Class')
plt.xlabel('Passenger Class')
plt.ylabel('Number of Passengers')
plt.xticks([0, 1, 2], ['1st Class', '2nd Class', '3rd Class'])
plt.legend(title='Survived', labels=['No', 'Yes'])

plt.show()

plt.figure(figsize=(8, 5))

sns.histplot(data=df, x='Age', bins=30, kde=True, color='skyblue')

plt.title('Age Distribution of Titanic Passengers')
plt.xlabel('Age')
plt.ylabel('Number of Passengers')

plt.show()

plt.figure(figsize=(8, 5))

sns.scatterplot(data=df, x='Age', y='Fare', hue='Survived', palette='Set1', alpha=0.7)

plt.title('Relationship Between Age and Fare')
plt.xlabel('Age')
plt.ylabel('Ticket Fare')

plt.show()

plt.figure(figsize=(10, 6))

correlation = df.select_dtypes(include='number').corr()

sns.heatmap(correlation, annot=True, cmap='coolwarm', fmt='.2f')

plt.title('Correlation Heatmap of Titanic Dataset')

plt.show()

plt.figure(figsize=(8, 5))

sns.boxplot(data=df, x='Survived', y='Age', hue='Survived', palette='Set2', legend=False)

plt.title('Age Distribution by Survival Status')
plt.xlabel('Survival Status (0 = No, 1 = Yes)')
plt.ylabel('Age')
plt.xticks([0, 1], ['Not Survived', 'Survived'])

plt.show()

# Pairplot of selected numerical columns

sns.pairplot(
    df[['Survived', 'Pclass', 'Age', 'Fare']],
    hue='Survived',
    palette='Set1'
)

plt.show()